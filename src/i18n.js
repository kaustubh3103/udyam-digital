export function makeT(lang) {
  const chain = [DICTS[lang] || {}, lang === "en" ? {} : hi, en];
  const get = (path) => {
    for (const d of chain) {
      let v = d;
      for (const k of path) v = v?.[k];
      if (v !== undefined) return v;
    }
    return path.join(".");
  };
  return (key, ...args) => {
    const v = get(key.split("."));
    return typeof v === "function" ? v(...args) : v;
  };
}

